export function AgentIcon({ agentKey, size = 18, className = "" }) {
  const key = (agentKey || '').toLowerCase();
  switch (key) {
    case 'jarvis':
    case 'supervisor':
      return <JarvisIcon size={size} className={className} />;
    case 'sentinel':
      return <SentinelIcon size={size} className={className} />;
    case 'hermes':
      return <HermesIcon size={size} className={className} />;
    case 'scout':
      return <ScoutIcon size={size} className={className} />;
    case 'scribe':
      return <ScribeIcon size={size} className={className} />;
    case 'cipher':
      return <CipherIcon size={size} className={className} />;
    case 'chronos':
      return <ChronosIcon size={size} className={className} />;
    default:
      return <BotIcon size={size} className={className} />;
  }
}
